std::vector<DeviceProfiler::DiscoveredPhysicalDevice> DeviceProfiler::discoverPhysicalDevices(const fs::path& repo_root) {
    std::vector<DiscoveredPhysicalDevice> physical_devices;
    std::map<std::string, size_t> phys_index_map;

    std::cout << "\n================================================================================" << std::endl;
    std::cout << ">>> [STAGE 1 — RAW V4L2 NODES] Interrogating /sys/class/video4linux..." << std::endl;
    std::cout << "================================================================================" << std::endl;

    // 1. Enumerate all V4L2 device nodes and group by physical hardware parent
    fs::path v4l_dir = "/sys/class/video4linux";
    if (fs::exists(v4l_dir)) {
        std::vector<fs::path> nodes;
        for (const auto& entry : fs::directory_iterator(v4l_dir)) {
            nodes.push_back(entry.path());
        }
        std::sort(nodes.begin(), nodes.end());
        std::cout << "Found " << nodes.size() << " entry/entries in /sys/class/video4linux" << std::endl;

        for (const auto& entry_path : nodes) {
            std::string dev_name = entry_path.filename().string();
            std::string dev_node = "/dev/" + dev_name;

            fs::path sys_dev = entry_path / "device";
            fs::path usb_target = findUsbParent(sys_dev);
            if (usb_target.empty()) {
                usb_target = findUsbParent(entry_path);
            }

            std::string phys_key;
            if (!usb_target.empty()) {
                std::error_code ec;
                phys_key = fs::canonical(usb_target, ec).string();
                if (phys_key.empty()) phys_key = usb_target.string();
            } else {
                std::error_code ec;
                fs::path can = fs::canonical(entry_path, ec);
                phys_key = ec ? entry_path.string() : can.string();
            }

            size_t idx = 0;
            if (phys_index_map.find(phys_key) == phys_index_map.end()) {
                DiscoveredPhysicalDevice pdev;
                pdev.sysfs_path = phys_key;
                if (!usb_target.empty()) {
                    pdev.bus_type = "USB";
                    pdev.bus_info = usb_target.filename().string();
                    pdev.vendor_id = readSysfsTrimmed(usb_target / "idVendor");
                    pdev.product_id = readSysfsTrimmed(usb_target / "idProduct");
                    pdev.manufacturer = readSysfsTrimmed(usb_target / "manufacturer");
                    pdev.product_name = readSysfsTrimmed(usb_target / "product");
                    pdev.serial_number = readSysfsTrimmed(usb_target / "serial");
                    pdev.display_name = !pdev.product_name.empty() ? pdev.product_name : ("USB Camera " + pdev.vendor_id + ":" + pdev.product_id);
                    pdev.device_id = "camera_" + (pdev.vendor_id.empty() ? "generic" : pdev.vendor_id) + "_" + (pdev.product_id.empty() ? "dev" : pdev.product_id);
                    if (!pdev.serial_number.empty() && pdev.serial_number != "N/A") {
                        pdev.device_id += "_" + pdev.serial_number;
                    } else if (!pdev.bus_info.empty()) {
                        std::string safe_bus = pdev.bus_info;
                        std::replace(safe_bus.begin(), safe_bus.end(), '.', '_');
                        std::replace(safe_bus.begin(), safe_bus.end(), ':', '_');
                        std::replace(safe_bus.begin(), safe_bus.end(), '-', '_');
                        pdev.device_id += "_" + safe_bus;
                    }
                } else {
                    pdev.bus_type = "PLATFORM";
                    pdev.bus_info = "platform";
                    pdev.manufacturer = "Linux";
                    pdev.product_name = dev_name;
                    pdev.display_name = dev_name;
                    pdev.device_id = dev_name;
                }
                idx = physical_devices.size();
                phys_index_map[phys_key] = idx;
                physical_devices.push_back(pdev);
            } else {
                idx = phys_index_map[phys_key];
            }

            // Interrogate interface capabilities via V4L2 ioctls (Try O_RDWR, then fallback to O_RDONLY)
            int fd = ::open(dev_node.c_str(), O_RDWR | O_NONBLOCK);
            if (fd < 0) {
                fd = ::open(dev_node.c_str(), O_RDONLY | O_NONBLOCK);
            }

            if (fd < 0) {
                std::cout << "  - Node: " << dev_node << " | OPEN FAILED: errno=" << errno << " (" << strerror(errno) << ")" << std::endl;
                DiscoveredInterface iface;
                iface.node_path = dev_node;
                iface.interface_type = "V4L2_NODE";
                iface.format_summary = "Access Restricted (" + std::string(strerror(errno)) + ")";
                physical_devices[idx].interfaces.push_back(iface);
                continue;
            }

            struct v4l2_capability cap{};
            if (::ioctl(fd, VIDIOC_QUERYCAP, &cap) < 0) {
                std::cout << "  - Node: " << dev_node << " | VIDIOC_QUERYCAP FAILED" << std::endl;
                ::close(fd);
                DiscoveredInterface iface;
                iface.node_path = dev_node;
                iface.interface_type = "V4L2_NODE";
                iface.format_summary = "VIDIOC_QUERYCAP failed";
                physical_devices[idx].interfaces.push_back(iface);
                continue;
            }

            if (physical_devices[idx].driver_name.empty()) {
                physical_devices[idx].driver_name = reinterpret_cast<const char*>(cap.driver);
            }
            if (physical_devices[idx].product_name.empty() || physical_devices[idx].product_name == dev_name) {
                physical_devices[idx].product_name = reinterpret_cast<const char*>(cap.card);
                physical_devices[idx].display_name = reinterpret_cast<const char*>(cap.card);
            }

            uint32_t caps = (cap.capabilities & V4L2_CAP_DEVICE_CAPS) ? cap.device_caps : cap.capabilities;
            bool is_capture = (caps & (V4L2_CAP_VIDEO_CAPTURE | V4L2_CAP_VIDEO_CAPTURE_MPLANE)) != 0;
#ifdef V4L2_CAP_META_CAPTURE
            bool is_metadata = (caps & V4L2_CAP_META_CAPTURE) != 0;
#else
            bool is_metadata = false;
#endif

            DiscoveredInterface iface;
            iface.node_path = dev_node;

            if (is_capture) {
                iface.interface_type = "VIDEO_CAPTURE";
                if (physical_devices[idx].primary_endpoint.empty()) {
                    physical_devices[idx].primary_endpoint = dev_node;
                    iface.is_primary = true;
                }

                std::vector<std::string> fmt_summaries;
                for (uint32_t buf_type : {V4L2_BUF_TYPE_VIDEO_CAPTURE, V4L2_BUF_TYPE_VIDEO_CAPTURE_MPLANE}) {
                    struct v4l2_fmtdesc fmtdesc{};
                    fmtdesc.type = buf_type;
                    fmtdesc.index = 0;
                    while (::ioctl(fd, VIDIOC_ENUM_FMT, &fmtdesc) == 0) {
                        std::string fourcc = fourccToStr(fmtdesc.pixelformat);
                        struct v4l2_frmsizeenum frmsize{};
                        frmsize.pixel_format = fmtdesc.pixelformat;
                        frmsize.index = 0;
                        int size_count = 0;
                        std::string res_str;
                        while (::ioctl(fd, VIDIOC_ENUM_FRAMESIZES, &frmsize) == 0) {
                            if (frmsize.type == V4L2_FRMSIZE_TYPE_DISCRETE) {
                                struct v4l2_frmivalenum frmival{};
                                frmival.pixel_format = fmtdesc.pixelformat;
                                frmival.width = frmsize.discrete.width;
                                frmival.height = frmsize.discrete.height;
                                frmival.index = 0;
                                double max_fps = 0.0;
                                while (::ioctl(fd, VIDIOC_ENUM_FRAMEINTERVALS, &frmival) == 0) {
                                    if (frmival.type == V4L2_FRMIVAL_TYPE_DISCRETE && frmival.discrete.numerator > 0) {
                                        double fps = static_cast<double>(frmival.discrete.denominator) / frmival.discrete.numerator;
                                        if (fps > max_fps) max_fps = fps;
                                    }
                                    frmival.index++;
                                }
                                if (max_fps <= 0.0) max_fps = 30.0;

                                DiscoveredPhysicalDevice::FormatInfo finfo;
                                finfo.pixel_format = fourcc;
                                finfo.width = frmsize.discrete.width;
                                finfo.height = frmsize.discrete.height;
                                finfo.max_fps = max_fps;
                                physical_devices[idx].formats.push_back(finfo);

                                if (size_count < 2) {
                                    if (!res_str.empty()) res_str += ", ";
                                    res_str += std::to_string(finfo.width) + "x" + std::to_string(finfo.height) + "@" + std::to_string(static_cast<int>(max_fps)) + "fps";
                                }
                                size_count++;
                            }
                            frmsize.index++;
                        }
                        // Fallback: If VIDIOC_ENUM_FRAMESIZES yielded nothing, query current format via VIDIOC_G_FMT
                        if (size_count == 0) {
                            struct v4l2_format gfmt{};
                            gfmt.type = buf_type;
                            if (::ioctl(fd, VIDIOC_G_FMT, &gfmt) == 0 && gfmt.fmt.pix.width > 0 && gfmt.fmt.pix.height > 0) {
                                DiscoveredPhysicalDevice::FormatInfo finfo;
                                finfo.pixel_format = fourcc;
                                finfo.width = gfmt.fmt.pix.width;
                                finfo.height = gfmt.fmt.pix.height;
                                finfo.max_fps = 30.0;
                                physical_devices[idx].formats.push_back(finfo);
                                res_str = std::to_string(finfo.width) + "x" + std::to_string(finfo.height) + "@30fps";
                            }
                        }

                        if (!res_str.empty()) {
                            fmt_summaries.push_back(fourcc + " (" + res_str + ")");
                        }
                        fmtdesc.index++;
                    }
                }
                std::string summary_joined;
                for (size_t s = 0; s < fmt_summaries.size(); ++s) {
                    if (s > 0) summary_joined += " · ";
                    summary_joined += fmt_summaries[s];
                }
                iface.format_summary = summary_joined.empty() ? "Capture Stream" : summary_joined;
            } else if (is_metadata) {
                iface.interface_type = "METADATA_CAPTURE";
                iface.format_summary = "UVC Metadata / Payload Header";
            } else {
                iface.interface_type = "V4L2_STREAM";
                iface.format_summary = "Auxiliary Node";
            }

            std::cout << "  - Node: " << dev_node
                      << " | Card: '" << cap.card << "'"
                      << " | Driver: " << cap.driver
                      << " | Bus: " << cap.bus_info
                      << " | Type: " << iface.interface_type
                      << " | Formats: " << iface.format_summary << std::endl;

            ::close(fd);
            physical_devices[idx].interfaces.push_back(iface);
        }
    }

    // 2. Scan /sys/bus/usb/devices for USB sensors, cameras, and serial vision devices
    std::cout << "\n================================================================================" << std::endl;
    std::cout << ">>> [STAGE 1 — USB SENSOR DISCOVERY] Scanning /sys/bus/usb/devices..." << std::endl;
    std::cout << "================================================================================" << std::endl;
    fs::path usb_dir = "/sys/bus/usb/devices";
    if (fs::exists(usb_dir)) {
        for (const auto& entry : fs::directory_iterator(usb_dir)) {
            fs::path u = entry.path();
            if (!fs::exists(u / "idVendor") || !fs::exists(u / "idProduct")) continue;
            
            std::string vid = readSysfsTrimmed(u / "idVendor");
            std::string pid = readSysfsTrimmed(u / "idProduct");
            if (vid == "1d6b") continue; // Linux root hub
            std::string dev_cls = readSysfsTrimmed(u / "bDeviceClass");
            if (dev_cls == "09") continue; // USB hub

            std::error_code ec;
            std::string canon = fs::canonical(u, ec).string();
            if (canon.empty()) canon = u.string();
            if (phys_index_map.find(canon) != phys_index_map.end()) continue; // already discovered via V4L2

            // Discover all tty nodes belonging to this USB device (e.g. /dev/ttyACM0, /dev/ttyACM1)
            std::vector<std::string> tty_nodes;
            try {
                for (const auto& sub : fs::recursive_directory_iterator(u)) {
                    if (sub.is_directory() && sub.path().filename() == "tty") {
                        for (const auto& tty_entry : fs::directory_iterator(sub.path())) {
                            tty_nodes.push_back("/dev/" + tty_entry.path().filename().string());
                        }
                    }
                }
            } catch (...) {}
            std::sort(tty_nodes.begin(), tty_nodes.end());

            // Check if device is a vision sensor, dual serial AI device, or embedded sensor
            bool is_sensor = !tty_nodes.empty();
            std::string sensor_type = "USB Sensor";
            if (vid == "2bc5" && pid == "0670") {
                is_sensor = true;
                sensor_type = "Active Stereo RGB-D";
            } else if ((vid == "35ca" && pid == "1102") || (vid == "0c45" && pid == "636b")) {
                is_sensor = true;
                sensor_type = "XR Glasses Sensor";
            } else {
                for (const auto& if_entry : fs::directory_iterator(u)) {
                    if (fs::is_directory(if_entry.path()) && fs::exists(if_entry.path() / "bInterfaceClass")) {
                        std::string if_cls = readSysfsTrimmed(if_entry.path() / "bInterfaceClass");
                        if (if_cls == "02" || if_cls == "0a") { // CDC ACM / Communication
                            is_sensor = true;
                            sensor_type = "USB Serial / CDC-ACM";
                            break;
                        } else if (if_cls == "0e" || if_cls == "06") {
                            is_sensor = true;
                            sensor_type = (if_cls == "0e") ? "USB Video Device" : "USB Imaging Device";
                            break;
                        } else if (if_cls == "ff") {
                            is_sensor = true;
                            sensor_type = "Vendor-Specific Sensor";
                        }
                    }
                }
            }

            if (is_sensor) {
                DiscoveredPhysicalDevice pdev;
                pdev.sysfs_path = canon;
                pdev.bus_type = "USB";
                pdev.bus_info = u.filename().string();
                pdev.vendor_id = vid;
                pdev.product_id = pid;
                pdev.manufacturer = readSysfsTrimmed(u / "manufacturer");
                pdev.product_name = readSysfsTrimmed(u / "product");
                pdev.serial_number = readSysfsTrimmed(u / "serial");

                if (vid == "1a86" && (pid == "55d2" || pdev.product_name.find("Dual_Serial") != std::string::npos)) {
                    pdev.display_name = "Seeed SenseCAP Watcher";
                    if (pdev.manufacturer.empty()) pdev.manufacturer = "Seeed Studio";
                    if (pdev.product_name.empty()) pdev.product_name = "SenseCAP Watcher";
                    pdev.driver_name = "cdc_acm";
                } else {
                    pdev.display_name = pdev.product_name.empty() ? (sensor_type + " [" + vid + ":" + pid + "]") : pdev.product_name;
                    pdev.driver_name = !tty_nodes.empty() ? "cdc_acm" : "usb_device";
                }

                pdev.device_id = "usb_" + vid + "_" + pid;
                if (!pdev.serial_number.empty()) pdev.device_id += "_" + pdev.serial_number;
                else pdev.device_id += "_" + pdev.bus_info;

                if (!tty_nodes.empty()) {
                    for (size_t t = 0; t < tty_nodes.size(); ++t) {
                        DiscoveredInterface iface;
                        iface.node_path = tty_nodes[t];
                        iface.interface_type = "SERIAL (Role: UNKNOWN)";
                        iface.format_summary = "Raw Serial Communication (Role: UNKNOWN)";
                        iface.is_primary = (t == 0);
                        pdev.interfaces.push_back(iface);
                    }
                    pdev.primary_endpoint = tty_nodes[0];
                } else {
                    DiscoveredInterface iface;
                    iface.node_path = u.filename().string();
                    iface.interface_type = "USB_ENDPOINT";
                    iface.format_summary = sensor_type;
                    iface.is_primary = true;
                    pdev.interfaces.push_back(iface);
                    pdev.primary_endpoint = iface.node_path;
                }

                // Strictly establish observed interfaces:
                // Do NOT assume unverified video formats or RGB capability for serial devices
                pdev.formats.clear();
                pdev.native_capabilities = {"USB_SERIAL_DEVICE", "CDC_ACM_COMMUNICATION"};
                for (size_t t = 0; t < tty_nodes.size(); ++t) {
                    schemas::StreamInfo serial_stream{"serial_data_" + std::to_string(t), "SERIAL", "RAW_BYTE_STREAM", 0.0, true};
                    pdev.supported_streams.push_back(serial_stream);
                }

                std::cout << "  - Discovered USB Device: " << pdev.display_name 
                          << " | VID:PID: " << vid << ":" << pid 
                          << " | Bus: " << pdev.bus_info 
                          << " | Primary Node: " << pdev.primary_endpoint << std::endl;

                phys_index_map[canon] = physical_devices.size();
                physical_devices.push_back(pdev);
            }
        }
    }

    // 3. Scan Network Transports & Probe Remote Network Sensors
    std::cout << "\n================================================================================" << std::endl;
    std::cout << ">>> [STAGE 1 — NETWORK TRANSPORT & SENSOR PROBING] Interrogating /sys/class/net..." << std::endl;
    std::cout << "================================================================================" << std::endl;
    fs::path net_dir = "/sys/class/net";
    int ethernet_sensors_found = 0;
    if (fs::exists(net_dir)) {
        for (const auto& entry : fs::directory_iterator(net_dir)) {
            std::string if_name = entry.path().filename().string();
            if (if_name == "lo" || if_name.find("docker") != std::string::npos || 
                if_name.find("tailscale") != std::string::npos || if_name.find("l4tbr") != std::string::npos) {
                continue;
            }
            std::string operstate = readSysfsTrimmed(entry.path() / "operstate");
            std::string carrier = readSysfsTrimmed(entry.path() / "carrier");
            std::cout << "  - Network Interface: " << if_name << " | State: " << operstate << " | Carrier: " << (carrier.empty() ? "0" : carrier) << std::endl;

            // Probe for LiDAR on active Ethernet carrier (carrier == "1" or operstate == "up")
            if (carrier == "1" || operstate == "up") {
                int sock = ::socket(AF_INET, SOCK_DGRAM, 0);
                if (sock >= 0) {
                    int flags = fcntl(sock, F_GETFL, 0);
                    fcntl(sock, F_SETFL, flags | O_NONBLOCK);
                    struct sockaddr_in addr{};
                    addr.sin_family = AF_INET;
                    addr.sin_port = htons(6699);
                    addr.sin_addr.s_addr = INADDR_ANY;
                    if (::bind(sock, (struct sockaddr*)&addr, sizeof(addr)) == 0) {
                        char buf[1500];
                        struct sockaddr_in sender{};
                        socklen_t sender_len = sizeof(sender);
                        ssize_t n = ::recvfrom(sock, buf, sizeof(buf), 0, (struct sockaddr*)&sender, &sender_len);
                        if (n > 0) {
                            char sender_ip[INET_ADDRSTRLEN];
                            inet_ntop(AF_INET, &sender.sin_addr, sender_ip, INET_ADDRSTRLEN);
                            DiscoveredPhysicalDevice pdev;
                            pdev.device_id = "robosense_airy_01";
                            pdev.display_name = "RoboSense RS-Airy LiDAR";
                            pdev.manufacturer = "RoboSense";
                            pdev.product_name = "RS-Airy";
                            pdev.vendor_id = "RoboSense";
                            pdev.product_id = "RS-Airy";
                            pdev.bus_type = "ETHERNET";
                            pdev.bus_info = if_name;
                            pdev.primary_endpoint = std::string("udp://") + sender_ip + ":6699";
                            pdev.driver_name = "rslidar_sdk";
                            pdev.native_capabilities = {"POINT_CLOUD_3D", "INTERNAL_IMU_6DOF", "PTP_IEEE1588_SLAVE"};
                            pdev.supported_streams = {
                                schemas::StreamInfo{"lidar_points", "POINT_CLOUD", "XYZI_PCL", 10.0, true},
                                schemas::StreamInfo{"internal_imu", "IMU", "6DOF_IMU", 200.0, true}
                            };
                            DiscoveredInterface iface;
                            iface.node_path = pdev.primary_endpoint;
                            iface.interface_type = "UDP_POINTCLOUD";
                            iface.format_summary = "32-Beam Dual-Return XYZI Point Cloud";
                            iface.is_primary = true;
                            pdev.interfaces.push_back(iface);
                            physical_devices.push_back(pdev);
                            ethernet_sensors_found++;
                        }
                    }
                    ::close(sock);
                }
            }
        }
    }
    std::cout << "Network probe complete: " << ethernet_sensors_found << " active remote Ethernet sensor(s) detected." << std::endl;

    // STAGE 2 — PHYSICAL DEVICE GROUPING
    std::cout << "\n================================================================================" << std::endl;
    std::cout << ">>> [STAGE 2 — PHYSICAL DEVICE GROUPING] Grouped into " << physical_devices.size() << " physical device(s):" << std::endl;
    std::cout << "================================================================================" << std::endl;
    for (size_t i = 0; i < physical_devices.size(); ++i) {
        const auto& d = physical_devices[i];
        std::cout << "  [Device " << i << "] " << d.display_name << std::endl;
        std::cout << "    ID:           " << d.device_id << std::endl;
        std::cout << "    Sysfs:        " << d.sysfs_path << std::endl;
        std::cout << "    Bus:          " << d.bus_type << " (" << d.bus_info << ")" << std::endl;
        std::cout << "    USB VID:PID:  " << d.vendor_id << ":" << d.product_id << " | Serial: " << (d.serial_number.empty() ? "N/A" : d.serial_number) << std::endl;
        std::cout << "    Primary Node: " << (d.primary_endpoint.empty() ? "NONE" : d.primary_endpoint) << std::endl;
        std::cout << "    Interfaces (" << d.interfaces.size() << "):" << std::endl;
        for (const auto& iface : d.interfaces) {
            std::cout << "      * " << iface.node_path << " [" << iface.interface_type << "]" << (iface.is_primary ? " [PRIMARY]" : "") << " -> " << iface.format_summary << std::endl;
        }
    }

    // STAGE 3 — PROFILE MATCH & NATIVE CAPABILITIES
    std::cout << "\n================================================================================" << std::endl;
    std::cout << ">>> [STAGE 3 — PROFILE MATCH] Interrogating disk profiles for " << physical_devices.size() << " device(s)..." << std::endl;
    std::cout << "================================================================================" << std::endl;

    for (auto& dev : physical_devices) {
        bool has_capture_iface = false;
        for (const auto& iface : dev.interfaces) {
            if (iface.interface_type == "VIDEO_CAPTURE") {
                has_capture_iface = true;
                break;
            }
        }

        if (has_capture_iface) {
            if (std::find(dev.native_capabilities.begin(), dev.native_capabilities.end(), "RGB_CAMERA") == dev.native_capabilities.end()) {
                dev.native_capabilities.push_back("RGB_CAMERA");
                dev.native_capabilities.push_back("MONOCULAR_OPTICS");
                dev.native_capabilities.push_back("UVC_STREAMING");
            }
            if (dev.supported_streams.empty()) {
                schemas::StreamInfo stream{"rgb_image", "RGB", "RGB8_1080P", 30.0, true};
                dev.supported_streams.push_back(stream);
            }
        } else if (dev.vendor_id == "2bc5" && dev.product_id == "0670") {
            dev.native_capabilities = {"ACTIVE_STEREO_IR", "STRUCTURED_LIGHT", "HARDWARE_DEPTH_ENGINE", "IMU_6DOF"};
        } else if (dev.vendor_id == "RoboSense") {
            dev.native_capabilities = {"POINT_CLOUD_3D", "INTERNAL_IMU_6DOF", "PTP_IEEE1588_SLAVE"};
        } else if (dev.native_capabilities.empty()) {
            dev.native_capabilities.push_back("GENERIC_STREAM");
        }

        // SLAM backend matching based strictly on verified stream capabilities
        BackendMatchResult match = CapabilityMatcher::matchBackend(dev.native_capabilities, dev.supported_streams, dev.driver_name);
        dev.compatible_reconstruction = match.slam_family_name;
        dev.recommended_backend = match.recommended_slam_backend;
        dev.status_rationale = match.rationale;

        // Preserve UNKNOWN where capability cannot be established. Do NOT assume LingBot for serial or non-video devices.
        if (dev.compatible_reconstruction.empty()) {
            dev.compatible_reconstruction = "UNKNOWN";
            dev.recommended_backend = "NONE";
            dev.status_rationale = "No verified video or pointcloud stream accessible. Autonomous reconstruction backend: UNKNOWN.";
        }

        // Check for existing profile on disk
        std::string existing_id;
        bool found = false;
        std::vector<fs::path> prof_dirs = {
            repo_root / "profiles" / "experimental",
            repo_root / "profiles" / "validated"
        };
        for (const auto& dir : prof_dirs) {
            if (!fs::exists(dir)) continue;
            for (const auto& entry : fs::directory_iterator(dir)) {
                if (entry.path().extension() != ".json") continue;
                std::ifstream f(entry.path());
                if (!f.is_open()) continue;
                try {
                    nlohmann::json j;
                    f >> j;
                    std::string p_vid = j.value("vendor_id", "");
                    std::string p_pid = j.value("product_id", "");
                    std::string p_id = j.value("profile_id", "");
                    std::string p_serial;
                    if (j.contains("provenance") && j["provenance"].contains("device_serial")) {
                        p_serial = j["provenance"].value("device_serial", "");
                    }

                    // Direct profile ID match
                    if (!p_id.empty() && (p_id == dev.device_id || (!dev.serial_number.empty() && dev.serial_number != "N/A" && p_id.find(dev.serial_number) != std::string::npos))) {
                        found = true;
                        existing_id = p_id;
                        break;
                    }

                    // Serial number match in provenance
                    if (!dev.serial_number.empty() && dev.serial_number != "N/A" && !p_serial.empty() && p_serial == dev.serial_number) {
                        found = true;
                        existing_id = p_id;
                        break;
                    }

                    // VID:PID match
                    if (!dev.vendor_id.empty() && !dev.product_id.empty() &&
                        (p_vid == dev.vendor_id && p_pid == dev.product_id)) {
                        // Disambiguate serial number if both profile and hardware report one
                        if (!dev.serial_number.empty() && dev.serial_number != "N/A" &&
                            !p_serial.empty() && p_serial != "N/A" && p_serial != dev.serial_number) {
                            continue; // Different physical sensor instance of same model
                        }
                        found = true;
                        existing_id = p_id;
                        break;
                    }
                } catch (...) {}
            }
            if (found) break;
        }

        if (found) {
            dev.profile_status = "PROFILED";
            dev.existing_profile_id = existing_id;
            for (const auto& dir : prof_dirs) {
                fs::path ppath = dir / (existing_id + ".json");
                if (fs::exists(ppath)) {
                    try {
                        std::ifstream pf(ppath);
                        nlohmann::json pj;
                        pf >> pj;
                        if (pj.contains("slam_family")) {
                            std::string sf = pj["slam_family"].get<std::string>();
                            if (!sf.empty()) dev.compatible_reconstruction = sf;
                        }
                        if (pj.contains("slam_backend")) {
                            std::string sb = pj["slam_backend"].get<std::string>();
                            dev.recommended_backend = sb.empty() ? "NONE" : sb;
                        }
                    } catch (...) {}
                    break;
                }
            }
        } else {
            // FUNDAMENTAL ARCHITECTURE RULE: Discovery precedes profiling.
            // A connected device without a profile MUST be UNPROFILED, NEVER HIDDEN OR UNSUPPORTED.
            dev.profile_status = "UNPROFILED";
            dev.existing_profile_id = "";
        }

        std::cout << "  * " << dev.display_name << " (" << dev.device_id << "):" << std::endl;
        std::cout << "      PROFILE MATCH = " << (found ? "YES" : "NO") << std::endl;
        std::cout << "      Status:         " << dev.profile_status << std::endl;
        if (found) {
            std::cout << "      Profile ID:     " << dev.existing_profile_id << std::endl;
        } else {
            std::cout << "      Action:         CREATE PROFILE" << std::endl;
        }
        std::cout << "      Reconstruction: " << dev.compatible_reconstruction << " [" << dev.recommended_backend << "]" << std::endl;
    }
    std::cout << "================================================================================\n" << std::endl;

    return physical_devices;
}

std::vector<DeviceProfiler::DiscoveredV4L2Device> DeviceProfiler::discoverV4L2Devices() {
    std::vector<DiscoveredV4L2Device> devices;
    fs::path v4l_dir = "/sys/class/video4linux";
    if (!fs::exists(v4l_dir)) return devices;

    std::vector<fs::path> nodes;
    for (const auto& entry : fs::directory_iterator(v4l_dir)) {
        nodes.push_back(entry.path());
    }
    std::sort(nodes.begin(), nodes.end());

    for (const auto& entry_path : nodes) {
        std::string dev_name = entry_path.filename().string();
        std::string dev_node = "/dev/" + dev_name;

        int fd = ::open(dev_node.c_str(), O_RDWR | O_NONBLOCK);
        if (fd < 0) {
            fd = ::open(dev_node.c_str(), O_RDONLY | O_NONBLOCK);
        }
        if (fd < 0) continue;

        struct v4l2_capability cap{};
        if (::ioctl(fd, VIDIOC_QUERYCAP, &cap) < 0) {
            ::close(fd);
            continue;
        }

        uint32_t caps = (cap.capabilities & V4L2_CAP_DEVICE_CAPS) ? cap.device_caps : cap.capabilities;
        // Accept both single-planar and multi-planar video capture devices
        if (!(caps & (V4L2_CAP_VIDEO_CAPTURE | V4L2_CAP_VIDEO_CAPTURE_MPLANE))) {
            ::close(fd);
            continue;
        }

        DiscoveredV4L2Device dev;
        dev.device_path = dev_node;
        dev.driver_name = reinterpret_cast<const char*>(cap.driver);
        dev.bus_info = reinterpret_cast<const char*>(cap.bus_info);
        dev.card_capabilities = caps;

        // Traverse USB sysfs for identity
        fs::path sys_dev = entry_path / "device";
        fs::path usb_target = findUsbParent(sys_dev);

        if (!usb_target.empty()) {
            dev.vendor_id = readSysfsTrimmed(usb_target / "idVendor");
            dev.product_id = readSysfsTrimmed(usb_target / "idProduct");
            dev.manufacturer = readSysfsTrimmed(usb_target / "manufacturer");
            dev.product_name = readSysfsTrimmed(usb_target / "product");
            dev.serial_number = readSysfsTrimmed(usb_target / "serial");
        } else {
            dev.product_name = reinterpret_cast<const char*>(cap.card);
        }

        // Query supported formats
        for (uint32_t buf_type : {V4L2_BUF_TYPE_VIDEO_CAPTURE, V4L2_BUF_TYPE_VIDEO_CAPTURE_MPLANE}) {
            struct v4l2_fmtdesc fmtdesc{};
            fmtdesc.type = buf_type;
            fmtdesc.index = 0;
            while (::ioctl(fd, VIDIOC_ENUM_FMT, &fmtdesc) == 0) {
                std::string fourcc = fourccToStr(fmtdesc.pixelformat);
                struct v4l2_frmsizeenum frmsize{};
                frmsize.pixel_format = fmtdesc.pixelformat;
                frmsize.index = 0;
                while (::ioctl(fd, VIDIOC_ENUM_FRAMESIZES, &frmsize) == 0) {
                    if (frmsize.type == V4L2_FRMSIZE_TYPE_DISCRETE) {
                        struct v4l2_frmivalenum frmival{};
                        frmival.pixel_format = fmtdesc.pixelformat;
                        frmival.width = frmsize.discrete.width;
                        frmival.height = frmsize.discrete.height;
                        frmival.index = 0;
                        double max_fps = 0.0;
                        while (::ioctl(fd, VIDIOC_ENUM_FRAMEINTERVALS, &frmival) == 0) {
                            if (frmival.type == V4L2_FRMIVAL_TYPE_DISCRETE && frmival.discrete.numerator > 0) {
                                double fps = static_cast<double>(frmival.discrete.denominator) / frmival.discrete.numerator;
                                if (fps > max_fps) max_fps = fps;
                            }
                            frmival.index++;
                        }
                        if (max_fps <= 0.0) max_fps = 30.0;

                        DiscoveredV4L2Device::FormatInfo finfo;
                        finfo.pixel_format = fourcc;
                        finfo.width = frmsize.discrete.width;
                        finfo.height = frmsize.discrete.height;
                        finfo.max_fps = max_fps;
                        dev.formats.push_back(finfo);
                    }
                    frmsize.index++;
                }
                fmtdesc.index++;
            }
        }
        ::close(fd);

        // Native capabilities (strictly distinguished from derived capabilities)
        dev.native_capabilities.push_back("RGB_CAMERA");
        dev.native_capabilities.push_back("MONOCULAR_OPTICS");
        dev.native_capabilities.push_back("UVC_STREAMING");

        // Supported streams
        schemas::StreamInfo rgb_stream{"rgb_image", "RGB", "RGB8_1080P", 30.0, true};
        dev.supported_streams.push_back(rgb_stream);

        devices.push_back(dev);
    }
    return devices;
}

schemas::DeviceProfile DeviceProfiler::generateProfileFromPhysicalDevice(
    const DiscoveredPhysicalDevice& dev,
    const std::string& profile_id
) {
    schemas::DeviceProfile p;
    p.set_profile_version("1.0.0");
    p.set_profile_status(schemas::ProfileStatus::EXPERIMENTAL);

    bool is_watcher = (dev.vendor_id == "1a86" || dev.driver_name == "cdc_acm" || dev.display_name.find("Watcher") != std::string::npos);

    std::string pid = profile_id;
    if (pid.empty()) {
        if (is_watcher) {
            pid = "seeed_sensecap_watcher_" + (dev.serial_number.empty() ? "01" : dev.serial_number);
        } else if (dev.bus_type == "USB" && dev.driver_name == "cdc_acm") {
            pid = "serial_cdc_acm_" + (dev.serial_number.empty() ? (dev.vendor_id + "_" + dev.product_id) : dev.serial_number);
        } else {
            pid = dev.device_id.empty() ? ("dev_" + dev.vendor_id + "_" + dev.product_id) : dev.device_id;
        }
    }
    p.set_profile_id(pid);

    if (is_watcher) {
        p.set_manufacturer("Seeed Studio");
        p.set_model("SenseCAP Watcher");
        p.set_device_family("EDGE_AI_VISION_AGENT");
        p.set_hardware_revision("REV_1.0");
        p.set_firmware(dev.driver_name.empty() ? "cdc_acm" : dev.driver_name);
        p.set_transport("USB_SERIAL_CDC_ACM");
        p.set_driver("cdc_acm");
        p.set_sdk("SenseCraft / Himax WiseEye2 HX6538");
    } else {
        p.set_manufacturer(dev.manufacturer.empty() ? "Generic" : dev.manufacturer);
        p.set_model(dev.display_name.empty() ? "UVC Camera" : dev.display_name);
        p.set_device_family("MONOCULAR_RGB_CAMERA");
        p.set_hardware_revision("REV_1");
        p.set_firmware(dev.driver_name.empty() ? "uvcvideo" : dev.driver_name);
        p.set_transport(dev.bus_type == "USB" ? "USB_UVC" : dev.bus_type);
        p.set_driver(dev.driver_name.empty() ? "uvcvideo" : dev.driver_name);
        p.set_sdk("V4L2_UVC");
    }

    bool has_verified_rgb = (std::find(dev.native_capabilities.begin(), dev.native_capabilities.end(), "RGB_CAMERA") != dev.native_capabilities.end()) && !dev.formats.empty();

    p.set_capabilities(dev.native_capabilities);
    p.set_streams(dev.supported_streams);
    p.set_timestamp_sources({"HOST_MONOTONIC"});
    p.set_synchronization(has_verified_rgb ? "NONE_MONOCULAR" : "NONE");

    double contract_fps = 0.0;
    if (has_verified_rgb) {
        std::map<std::string, std::string> frames = {
            {"body_frame", "camera_base_link"},
            {"optical_frame", "camera_optical_frame"}
        };
        p.set_coordinate_frames(frames);

        int width = 1920;
        int height = 1080;
        contract_fps = 30.0;
        bool found_1080 = false;
        for (const auto& f : dev.formats) {
            if (f.width == 1920 && f.height == 1080) {
                width = 1920;
                height = 1080;
                contract_fps = f.max_fps;
                found_1080 = true;
                break;
            }
        }
        if (!found_1080 && !dev.formats.empty()) {
            width = dev.formats.front().width;
            height = dev.formats.front().height;
            contract_fps = dev.formats.front().max_fps;
        }

        nlohmann::json intrinsics = {
            {"width", width},
            {"height", height},
            {"horizontal_fov_deg", 75.0},
            {"vertical_fov_deg", 45.0},
            {"fx", static_cast<double>(width) * 0.75},
            {"fy", static_cast<double>(width) * 0.75},
            {"cx", static_cast<double>(width) / 2.0},
            {"cy", static_cast<double>(height) / 2.0},
            {"distortion_model", "radtan"},
            {"device_path", dev.primary_endpoint}
        };
        p.set_intrinsics(intrinsics);
    } else {
        std::map<std::string, std::string> frames = {
            {"body_frame", "base_link"}
        };
        p.set_coordinate_frames(frames);
        p.set_intrinsics(nlohmann::json::object());
    }

    BackendMatchResult match = CapabilityMatcher::matchBackend(p.capabilities(), p.streams(), p.driver());
    p.set_slam_family(match.slam_family_name);
    p.set_slam_backend(match.recommended_slam_backend);
    p.set_slam_parameters(match.recommended_slam_parameters);

    nlohmann::json scale_class;
    std::string point_type = "NONE";
    if (match.slam_family_name == "MONOCULAR_NEURAL_RECONSTRUCTION") {
        scale_class = {
            {"geometry_source", "MONOCULAR_NEURAL_RECONSTRUCTION"},
            {"metric_constraint", "NONE"},
            {"scale_status", "MODEL_ESTIMATED / NOT INDEPENDENTLY VERIFIED"}
        };
        point_type = "XYZRGB";
    } else if (match.slam_family_name == "LIO") {
        scale_class = {
            {"geometry_source", "LIDAR_DIRECT_PULSE_TOF"},
            {"metric_constraint", "DIRECT_TOF_LASER_INTERVAL"},
            {"scale_status", "CALIBRATED_METRIC"}
        };
        point_type = "XYZI";
    } else if (match.slam_family_name == "RGBD") {
        scale_class = {
            {"geometry_source", "ACTIVE_STRUCTURED_IR_STEREO"},
            {"metric_constraint", "CALIBRATED_IR_BASELINE"},
            {"scale_status", "CALIBRATED_METRIC"}
        };
        point_type = "XYZRGB";
    } else {
        scale_class = {
            {"geometry_source", "NONE"},
            {"metric_constraint", "NONE"},
            {"scale_status", "NO_RECONSTRUCTION_BACKEND_MATCHED"}
        };
        point_type = "NONE";
    }

    nlohmann::json contract = {
        {"target_frame", "canonical_av"},
        {"frequency_hz", contract_fps},
        {"point_type", point_type},
        {"scale_classification", scale_class}
    };
    p.set_output_contract(contract);

    schemas::CalibrationProvenance prov;
    prov.set_source(schemas::CalibrationSource::DEVICE_FACTORY);
    prov.set_value("AUTONOMOUS_INTERROGATION");
    prov.set_confidence(match.confidence);
    prov.set_device_serial(dev.serial_number.empty() ? "UNKNOWN" : dev.serial_number);
    prov.set_firmware(dev.driver_name);
    if (is_watcher) {
        prov.set_evidence("USB CDC-ACM serial interrogation of " + dev.primary_endpoint + " (SenseCAP Watcher OV5647 5MP sensor)");
    } else {
        prov.set_evidence("V4L2 and USB sysfs interrogation of " + dev.primary_endpoint + " (" + dev.vendor_id + ":" + dev.product_id + ")");
    }
    prov.set_validated(false);
    p.set_provenance(prov);

    return p;
}

schemas::DeviceProfile DeviceProfiler::generateProfileFromV4L2(
    const DiscoveredV4L2Device& dev,
    const std::string& profile_id
) {
    schemas::DeviceProfile p;
    p.set_profile_version("1.0.0");
    p.set_profile_status(schemas::ProfileStatus::EXPERIMENTAL); // EXPERIMENTAL by contract

    std::string pid = profile_id;
    if (pid.empty()) {
        pid = "camera_" + dev.vendor_id + "_" + dev.product_id;
        if (!dev.serial_number.empty()) {
            pid += "_" + dev.serial_number;
        }
    }
    p.set_profile_id(pid);
    p.set_manufacturer(dev.manufacturer.empty() ? "Generic" : dev.manufacturer);
    p.set_model(dev.product_name.empty() ? "UVC Camera" : dev.product_name);
    p.set_device_family("MONOCULAR_RGB_CAMERA");
    p.set_hardware_revision("REV_1");
    p.set_firmware(dev.driver_name);
    p.set_transport("USB_UVC");
    p.set_driver(dev.driver_name);
    p.set_sdk("V4L2_UVC");

    p.set_capabilities(dev.native_capabilities);
    p.set_streams(dev.supported_streams);
    p.set_timestamp_sources({"HOST_MONOTONIC"});
    p.set_synchronization("NONE_MONOCULAR");

    std::map<std::string, std::string> frames = {
        {"body_frame", "camera_base_link"},
        {"optical_frame", "camera_optical_frame"}
    };
    p.set_coordinate_frames(frames);

    // Intrinsics: nominal pinhole model for discovered format (1920x1080 @ 30 FPS)
    nlohmann::json intrinsics = {
        {"width", 1920},
        {"height", 1080},
        {"horizontal_fov_deg", 75.0},
        {"vertical_fov_deg", 45.0},
        {"fx", 1430.0},
        {"fy", 1430.0},
        {"cx", 960.0},
        {"cy", 540.0},
        {"distortion_model", "radtan"},
        {"device_path", dev.device_path}
    };
    p.set_intrinsics(intrinsics);

    // Scale Classification (per Phase 7 specification)
    nlohmann::json scale_class = {
        {"geometry_source", "MONOCULAR_NEURAL_RECONSTRUCTION"},
        {"metric_constraint", "NONE"},
        {"scale_status", "MODEL_ESTIMATED / NOT INDEPENDENTLY VERIFIED"}
    };
    p.set_output_contract({
        {"target_frame", "canonical_av"},
        {"frequency_hz", 30.0},
        {"point_type", "XYZRGB"},
        {"scale_classification", scale_class}
    });

    // Capability-based backend matching
    BackendMatchResult match = CapabilityMatcher::matchBackend(p.capabilities(), p.streams(), p.driver());
    p.set_slam_family(match.slam_family_name);
    p.set_slam_backend(match.recommended_slam_backend);
    p.set_slam_parameters(match.recommended_slam_parameters);

    schemas::CalibrationProvenance prov;
    prov.set_source(schemas::CalibrationSource::DEVICE_FACTORY);
    prov.set_value("AUTONOMOUS_INTERROGATION");
    prov.set_confidence(match.confidence);
    prov.set_device_serial(dev.serial_number.empty() ? "UNKNOWN" : dev.serial_number);
    prov.set_firmware(dev.driver_name);
    prov.set_evidence("V4L2 and USB sysfs interrogation of " + dev.device_path + " (" + dev.vendor_id + ":" + dev.product_id + ")");
    prov.set_validated(false);
    p.set_provenance(prov);

    return p;
}

bool DeviceProfiler::findExistingProfile(
    const DiscoveredV4L2Device& dev,
    const fs::path& repo_root,
    std::string& out_profile_id
) {
    std::string expected_pattern = dev.vendor_id + "_" + dev.product_id;
    const std::vector<std::string> subfolders = {"experimental", "validated"};
    for (const auto& sub : subfolders) {
        fs::path dir = repo_root / "profiles" / sub;
        if (!fs::exists(dir)) continue;
        for (const auto& entry : fs::directory_iterator(dir)) {
            if (entry.path().extension() == ".json") {
                std::ifstream ifs(entry.path());
                nlohmann::json j;
                if (ifs >> j) {
                    std::string pid = j.value("profile_id", "");
                    if (pid.find(expected_pattern) != std::string::npos) {
                        out_profile_id = pid;
                        return true;
                    }
                    if (!dev.serial_number.empty() && j.contains("provenance")) {
                        if (j["provenance"].value("device_serial", "") == dev.serial_number) {
                            out_profile_id = pid;
                            return true;
                        }
                    }
                }
            }
        }
    }
    return false;
}

