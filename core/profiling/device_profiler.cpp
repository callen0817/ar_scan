bool DeviceProfiler::saveExperimentalProfile(
    const schemas::DeviceProfile& profile,
    const fs::path& repository_root,
    const std::string& filename
) {
    try {
        fs::path exp_dir = repository_root / "profiles" / "experimental";
        fs::create_directories(exp_dir);

        std::string fname = filename.empty() ? (profile.profile_id() + ".json") : filename;
        fs::path out_file = exp_dir / fname;

        std::ofstream ofs(out_file);
        if (!ofs.is_open()) {
            AV_LOG_ERROR("DeviceProfiler", "Save Failed", "Could not open " + out_file.string() + " for writing");
            return false;
        }

        ofs << profile.to_json().dump(2) << std::endl;
        AV_LOG_INFO("DeviceProfiler", "Saved experimental profile to: " + out_file.string());
        return true;
    } catch (const std::exception& e) {
        AV_LOG_ERROR("DeviceProfiler", "Save Exception", e.what());
        return false;
    }
}

