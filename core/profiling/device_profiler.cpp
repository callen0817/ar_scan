std::string readSysfsTrimmed(const fs::path& p) {
    if (!fs::exists(p)) return "";
    std::ifstream ifs(p);
    std::string val;
    if (std::getline(ifs, val)) {
        while (!val.empty() && (val.back() == '\r' || val.back() == '\n' || val.back() == ' ')) {
            val.pop_back();
        }
        return val;
    }
    return "";
}

std::string fourccToStr(uint32_t f) {
    char s[5] = {
        static_cast<char>(f & 0xFF),
        static_cast<char>((f >> 8) & 0xFF),
        static_cast<char>((f >> 16) & 0xFF),
        static_cast<char>((f >> 24) & 0xFF),
        0
    };
    return std::string(s);
}

fs::path findUsbParent(const fs::path& start) {
    std::error_code ec;
    fs::path p = fs::canonical(start, ec);
    if (ec || p.empty()) p = start;
    while (!p.empty() && p != p.root_path()) {
        if (fs::exists(p / "idVendor") && fs::exists(p / "idProduct")) {
            return p;
        }
        p = p.parent_path();
    }
    return {};
}

